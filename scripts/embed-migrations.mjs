// Embed each package's drizzle-kit SQL migrations into a TypeScript module so
// they ship inside the package (and inside the gateway bundle) with no
// filesystem lookup at runtime. Run from the repo root after `drizzle-kit
// generate` in a package: node scripts/embed-migrations.mjs
import fs from "node:fs";
import path from "node:path";

const OWNERS = [
  { dir: "packages/supplier-management", table: "__migrations_supplier_management", out: "src/migrations.ts", name: "supplierMigrations" },
  { dir: "packages/user-management", table: "__migrations_user_management", out: "src/migrations.ts", name: "userMigrations" },
  { dir: "packages/model-services", table: "__migrations_model_services", out: "src/migrations.ts", name: "modelServiceMigrations" },
  { dir: "packages/micro-agent", table: "__migrations_micro_agent", out: "src/migrations.ts", name: "microAgentMigrations" },
  { dir: "apps/gateway", table: "__migrations_gateway", out: "src/db/migrations.ts", name: "gatewayMigrations" },
];

for (const o of OWNERS) {
  const journalPath = path.join(o.dir, "drizzle", "meta", "_journal.json");
  if (!fs.existsSync(journalPath)) {
    console.warn(`skip ${o.dir}: no drizzle/meta/_journal.json`);
    continue;
  }
  const journal = JSON.parse(fs.readFileSync(journalPath, "utf8"));
  const entries = journal.entries.map((e) => {
    const sql = fs.readFileSync(path.join(o.dir, "drizzle", `${e.tag}.sql`), "utf8").replace(/\r\n/g, "\n");
    return `  {\n    tag: ${JSON.stringify(e.tag)},\n    sql: ${JSON.stringify(sql)},\n  },`;
  });
  const body =
    `// GENERATED by scripts/embed-migrations.mjs from ./drizzle -- do not edit by hand.\n` +
    `// Regenerate: npx drizzle-kit generate (in this package), then node scripts/embed-migrations.mjs (repo root).\n` +
    `import type { MigrationSet } from "@areelai/common";\n\n` +
    `export const ${o.name}: MigrationSet = {\n  table: ${JSON.stringify(o.table)},\n  migrations: [\n${entries.join("\n")}\n  ],\n};\n`;
  fs.writeFileSync(path.join(o.dir, o.out), body);
  console.log(`${o.dir}: ${entries.length} migration(s) -> ${o.out}`);
}
